#!/usr/bin/env python3
"""Render the README's before/after SVG from real Linelight output.

Run from a checkout after building:
    python3 docs/render-demo.py [path/to/linelight]

Uses only Python's standard library. User profiles and palettes are isolated.
"""

from html import escape
from pathlib import Path
import os
import re
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
SAMPLE = (
    "INFO  listening on 127.0.0.1:8080\n"
    "WARN  retrying /api/search\n"
    "ERROR database unavailable\n"
)
SGR = re.compile(r"\x1b\[([0-9;]*)m")
COLORS = {
    30: "#111820",
    31: "#ff7b86",
    32: "#8ddb8c",
    33: "#f0d278",
    34: "#8bb4ff",
    35: "#d9a0f1",
    36: "#80d4e8",
    37: "#e7edf5",
}
DEFAULT = "#d3dce8"


def spans(line):
    """Translate generated SGR runs without altering or inventing emphasis."""
    foreground = DEFAULT
    bold = False
    offset = 0
    pieces = []
    for match in SGR.finditer(line):
        if match.start() > offset:
            weight = ' font-weight="700"' if bold else ""
            pieces.append(
                f'<tspan fill="{foreground}"{weight}>'
                f"{escape(line[offset:match.start()])}</tspan>"
            )
        for code in map(int, match.group(1).split(";")):
            if code == 0:
                foreground, bold = DEFAULT, False
            elif code == 1:
                bold = True
            elif code in COLORS:
                foreground = COLORS[code]
            else:
                raise ValueError(f"Unsupported demo SGR parameter: {code}")
        offset = match.end()
    if offset < len(line):
        weight = ' font-weight="700"' if bold else ""
        pieces.append(
            f'<tspan fill="{foreground}"{weight}>'
            f"{escape(line[offset:])}</tspan>"
        )
    return "".join(pieces)


def main():
    binary = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else (
        ROOT / "target/release/linelight"
    )
    with tempfile.TemporaryDirectory(prefix="linelight-demo-") as directory:
        result = subprocess.run(
            [str(binary), "filter", "--profile", "log", "--color", "always"],
            input=SAMPLE.encode(),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env={
                "HOME": directory,
                "XDG_CONFIG_HOME": directory,
                "PATH": os.defpath,
                "LC_ALL": "C",
                "TERM": "xterm-256color",
            },
            check=True,
        )
    colored = result.stdout.decode()
    if SGR.sub("", colored) != SAMPLE or result.stderr:
        raise ValueError("Demo output changed the input or emitted a diagnostic")

    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="720" height="318" '
        'viewBox="0 0 720 318" role="img" aria-labelledby="title desc">',
        "  <title id=\"title\">Linelight: the same text, highlighted</title>",
        "  <desc id=\"desc\">Three log lines before and after the log profile. "
        "INFO is green, WARN is yellow, ERROR is red. The address and path "
        "are highlighted. Only styling changes.</desc>",
        "  <!-- Generated by docs/render-demo.py from the embedded log profile. "
        "Colors show one terminal palette; text and SGR runs are actual output. -->",
        '  <rect x="0.5" y="0.5" width="719" height="317" rx="12" '
        'fill="#111820" stroke="#304154"/>',
        '  <path d="M24 158H696" stroke="#304154"/>',
        '  <g font-family="DejaVu Sans Mono, monospace" font-size="20" '
        'xml:space="preserve">',
        '    <text x="26" y="32" fill="#a8b8cb" font-size="11" '
        'letter-spacing="1.5">PLAIN LOG OUTPUT</text>',
    ]
    for index, line in enumerate(SAMPLE.splitlines()):
        lines.append(
            f'    <text x="26" y="{70 + index * 30}" fill="{DEFAULT}">'
            f"{escape(line)}</text>"
        )
    lines.append(
        '    <text x="26" y="190" fill="#a8b8cb" font-size="11" '
        'letter-spacing="1.5">LINELIGHT / LOG PROFILE</text>'
    )
    for index, line in enumerate(colored.splitlines()):
        lines.append(
            f'    <text x="26" y="{228 + index * 30}">{spans(line)}</text>'
        )
    lines.extend(["  </g>", "</svg>", ""])
    target = ROOT / "docs/images/log-demo.svg"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines))
    print(target)


if __name__ == "__main__":
    main()
