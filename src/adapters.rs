use std::collections::BTreeSet;
use std::env;
use std::os::unix::fs::PermissionsExt;
use std::path::PathBuf;

use serde::Deserialize;

use crate::error::{Error, Result};
use crate::profile::ProfileSet;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct AdapterFile {
    #[serde(default = "default_schema")]
    schema: u32,
    #[serde(default)]
    disable: Vec<String>,
}

fn default_schema() -> u32 {
    1
}

pub fn generate(shell: &str, profile_dirs: &[PathBuf]) -> Result<String> {
    let disabled = disabled_commands()?;
    let set = ProfileSet::discover(profile_dirs);
    let mut commands = Vec::new();
    for id in set.entries.keys() {
        if id == "log" || id == "ls" || disabled.contains(id) {
            continue;
        }
        if command_on_path(id) {
            commands.push(id.as_str());
        }
    }
    commands.sort();
    commands.dedup();
    if commands.is_empty() {
        return Ok(String::new());
    }

    match shell {
        "bash" => Ok(bash(&commands)),
        "zsh" => Ok(zsh(&commands)),
        "tcsh" => Ok(tcsh(&commands)),
        "fish" => Ok(fish(&commands)),
        other => Err(Error::usage(format!(
            "unknown shell `{}`; expected bash, zsh, tcsh, or fish",
            other
        ))),
    }
}

fn disabled_commands() -> Result<BTreeSet<String>> {
    let Some(path) = adapters_path() else {
        return Ok(BTreeSet::new());
    };
    if !path.is_file() {
        return Ok(BTreeSet::new());
    }
    let text = std::fs::read_to_string(&path)
        .map_err(|error| Error::new(format!("{}: {}", path.display(), error)))?;
    let file: AdapterFile = toml::from_str(&text)
        .map_err(|error| Error::new(format!("{}: {}", path.display(), error)))?;
    if file.schema != 1 {
        return Err(Error::new(format!(
            "{}: unsupported adapter schema {}; expected 1",
            path.display(),
            file.schema
        )));
    }
    Ok(file.disable.into_iter().collect())
}

fn adapters_path() -> Option<PathBuf> {
    let home = env::var_os("HOME").map(PathBuf::from);
    let config = env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .or_else(|| home.map(|home| home.join(".config")))?;
    Some(config.join("linelight/adapters.toml"))
}

fn command_on_path(name: &str) -> bool {
    let Some(path) = env::var_os("PATH") else {
        return false;
    };
    for dir in env::split_paths(&path) {
        let candidate = dir.join(name);
        if let Ok(metadata) = std::fs::metadata(&candidate) {
            if metadata.is_file() && metadata.permissions().mode() & 0o111 != 0 {
                return true;
            }
        }
    }
    false
}

fn bash(commands: &[&str]) -> String {
    let mut out = String::from(
        "# generated by `linelight init bash`\n\
         if [ \"${LINELIGHT_INIT:-1}\" != \"0\" ] && command -v linelight >/dev/null 2>&1; then\n",
    );
    for command in commands {
        out.push_str(&format!(
            "    if ! alias {0} >/dev/null 2>&1 && ! declare -F {0} >/dev/null 2>&1; then\n\
             \x20       eval '{0}() {{ command linelight run --profile {0} -- \"$(type -P {0})\" \"$@\"; }}'\n\
             \x20   fi\n",
            command
        ));
    }
    out.push_str("fi\n");
    out
}

fn zsh(commands: &[&str]) -> String {
    let mut out = String::from(
        "# generated by `linelight init zsh`\n\
         if [[ ${LINELIGHT_INIT:-1} != 0 ]] && (( $+commands[linelight] )); then\n",
    );
    for command in commands {
        out.push_str(&format!(
            "    if (( ! $+aliases[{0}] && ! $+functions[{0}] )); then\n\
             \x20       eval '{0}() {{ command linelight run --profile {0} -- \"${{commands[{0}]}}\" \"$@\"; }}'\n\
             \x20   fi\n",
            command
        ));
    }
    out.push_str("fi\n");
    out
}

fn tcsh(commands: &[&str]) -> String {
    // tcsh folds a command substitution inside double quotes into one line
    // before eval parses it. Keep every statement single-line, semicolon
    // terminated, and comment-free so both `eval "`linelight init tcsh`"` and
    // sourcing the output from a file work.
    let mut out = String::from(
        "if ( $?LINELIGHT_INIT ) eval 'set _linelight_enabled = \"$LINELIGHT_INIT\"';\n\
         if ( $?_linelight_enabled == 0 ) set _linelight_enabled = 1;\n\
         if ( \"$_linelight_enabled\" != 0 ) which linelight >& /dev/null;\n\
         if ( \"$_linelight_enabled\" != 0 && $status == 0 ) set _linelight_ready = 1;\n",
    );
    for command in commands {
        out.push_str(&format!(
            "if ( $?_linelight_ready && \"`alias {0}`\" == \"\" ) alias {0} 'linelight run --profile {0} -- \\{0} \\!*';\n",
            command
        ));
    }
    out.push_str("unset _linelight_enabled _linelight_ready;\n");
    out
}

fn fish(commands: &[&str]) -> String {
    let mut out = String::from(
        "# generated by `linelight init fish`\n\
         if test \"$LINELIGHT_INIT\" != 0; and command -sq linelight\n",
    );
    for command in commands {
        out.push_str(&format!(
            "    if not functions -q {0}\n\
             \x20       function {0} --wraps {0}\n\
             \x20           command linelight run --profile {0} -- (type -P {0}) $argv\n\
             \x20       end\n\
             \x20   end\n",
            command
        ));
    }
    out.push_str("end\n");
    out
}

#[cfg(test)]
mod tests {
    use super::{bash, fish, tcsh, zsh};

    #[test]
    fn generated_scripts_mention_commands() {
        let commands = ["df", "ping"];
        assert!(bash(&commands).contains("--profile df"));
        assert!(zsh(&commands).contains("--profile ping"));
        assert!(tcsh(&commands).contains("alias ping"));
        assert!(fish(&commands).contains("--profile df"));
    }
}
